def mask():
    im = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(im)
    def pt(p): return ((p[0] + 180) / 360 * W * SS, (90 - p[1]) / 180 * H * SS)
    for p in POLYS.values():
        d.polygon([pt(q) for q in p], fill=255)
    for p in WATER.values():
        d.polygon([pt(q) for q in p], fill=0)
    small = im.resize((W, H), Image.BOX)
    return [[small.getpixel((x, y)) >= 100 for x in range(W)] for y in range(H)]

def main():
    m = mask()
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if m[y][x]:
                bits |= 1 << x
        rows.append(bits)
    out = ["/* SPDX-License-Identifier: MPL-2.0 */",
           "/* GENERATED by tools/gen_land.py: the Earth's land, 72 x 36 cells of 5 degrees. A row is a 72-bit field in two",
           " * words: bit x of (lo, hi), x = 0 at 180 W; row 0 is 90 N. */",
           "#pragma once", "#include <stdint.h>", "#define LAND_W 72", "#define LAND_H 36",
           "static const uint32_t LAND[LAND_H][3] = {"]
    for y, b in enumerate(rows):
        out.append("    {0x%08Xu, 0x%08Xu, 0x%02Xu},   /* %3d N */" % (b & 0xFFFFFFFF, (b >> 32) & 0xFFFFFFFF, b >> 64, 90 - 5 * y - 2))
    out.append("};")
    open("app/land.h", "w").write("\n".join(out) + "\n")
    if "--preview" in sys.argv:
        pv = Image.new("RGB", (W * 8, H * 8), (20, 40, 90))
        d = ImageDraw.Draw(pv)
        for y in range(H):
            for x in range(W):
                if m[y][x]:
                    d.rectangle([x * 8, y * 8, x * 8 + 7, y * 8 + 7], fill=(80, 160, 70))
        pv.save(sys.argv[sys.argv.index("--preview") + 1])
    print("land cells:", sum(sum(r) for r in m), "of", W * H)

main()
